import hashlib
import hmac
import base64
import json
import time
import uuid
from typing import Optional, Tuple
from fastapi import Depends, HTTPException, status
from fastapi.security import OAuth2PasswordBearer
from sqlalchemy.orm import Session
from argon2 import PasswordHasher
from argon2.exceptions import VerifyMismatchError, VerificationError, InvalidHashError

from app.config import settings
from app.database import get_db
from app.models import User, RevokedToken

# Configure Argon2id password hasher with production-grade parameters
password_hasher = PasswordHasher(
    time_cost=2,
    memory_cost=65536,  # 64 MB
    parallelism=1,
    hash_len=32,
    salt_len=16
)

oauth2_scheme = OAuth2PasswordBearer(tokenUrl=f"{settings.API_V1_STR}/auth/login", auto_error=False)


def hash_password(password: str) -> str:
    """
    Hashes a password using Argon2id with a unique salt generated by the library.
    """
    return password_hasher.hash(password)


def verify_and_check_rehash(plain_password: str, hashed_password: str) -> Tuple[bool, bool]:
    """
    Verifies a password against the stored hash.
    Returns (is_valid, needs_rehash).
    Enables safe, seamless migration from legacy SHA-256 hashes to Argon2id.
    """
    if not plain_password or not hashed_password:
        return False, False

    # Check for Argon2 hash format ($argon2id$, $argon2i$, $argon2d$)
    if hashed_password.startswith("$argon2"):
        try:
            password_hasher.verify(hashed_password, plain_password)
            needs_rehash = password_hasher.check_needs_rehash(hashed_password)
            return True, needs_rehash
        except (VerifyMismatchError, VerificationError, InvalidHashError):
            return False, False

    # Legacy SHA-256 backward-compatibility fallback
    salt = settings.SECRET_KEY[:16]
    legacy_hash = hashlib.sha256((salt + plain_password).encode()).hexdigest()
    if hmac.compare_digest(legacy_hash, hashed_password):
        return True, True  # Valid credential, but needs rehashing to Argon2id

    return False, False


def verify_password(plain_password: str, hashed_password: str) -> bool:
    """Convenience wrapper returning boolean verification status."""
    is_valid, _ = verify_and_check_rehash(plain_password, hashed_password)
    return is_valid


def create_access_token(data: dict, expires_delta_sec: Optional[int] = None) -> str:
    """
    Generates a signed JWT with HS256, expiration, and unique JWT ID (jti) for revoking.
    """
    payload = data.copy()
    expire = int(time.time()) + (expires_delta_sec or settings.ACCESS_TOKEN_EXPIRE_MINUTES * 60)
    payload["exp"] = expire
    if "jti" not in payload:
        payload["jti"] = str(uuid.uuid4())

    header = {"alg": "HS256", "typ": "JWT"}
    hdr_b64 = base64.urlsafe_b64encode(json.dumps(header).encode()).decode().rstrip("=")
    payload_b64 = base64.urlsafe_b64encode(json.dumps(payload).encode()).decode().rstrip("=")

    sig = hmac.new(
        settings.SECRET_KEY.encode(),
        f"{hdr_b64}.{payload_b64}".encode(),
        hashlib.sha256
    ).digest()
    sig_b64 = base64.urlsafe_b64encode(sig).decode().rstrip("=")

    return f"{hdr_b64}.{payload_b64}.{sig_b64}"


def decode_token(token: str) -> Optional[dict]:
    """
    Validates token format, signature, and expiration. Returns payload dictionary if valid.
    """
    try:
        parts = token.split(".")
        if len(parts) != 3:
            return None
        hdr_b64, payload_b64, sig_b64 = parts

        # Verify HS256 signature
        expected_sig = hmac.new(
            settings.SECRET_KEY.encode(),
            f"{hdr_b64}.{payload_b64}".encode(),
            hashlib.sha256
        ).digest()

        rem = len(sig_b64) % 4
        padded_sig = sig_b64 + ("=" * (4 - rem) if rem else "")
        provided_sig = base64.urlsafe_b64decode(padded_sig.encode())

        if not hmac.compare_digest(expected_sig, provided_sig):
            return None

        rem_p = len(payload_b64) % 4
        padded_payload = payload_b64 + ("=" * (4 - rem_p) if rem_p else "")
        payload = json.loads(base64.urlsafe_b64decode(padded_payload.encode()).decode())

        if payload.get("exp", 0) < int(time.time()):
            return None  # expired token
        return payload
    except Exception:
        return None


def get_current_user(token: Optional[str] = Depends(oauth2_scheme), db: Session = Depends(get_db)) -> User:
    """
    Enforces authentication for private endpoints.
    Rejects unauthenticated access, expired tokens, revoked tokens, and deactivated users.
    """
    if not token:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authentication credentials required",
            headers={"WWW-Authenticate": "Bearer"},
        )

    payload = decode_token(token)
    if not payload:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or expired authentication credentials",
            headers={"WWW-Authenticate": "Bearer"},
        )

    # Check token revocation
    jti = payload.get("jti")
    if jti:
        is_revoked = db.query(RevokedToken).filter(RevokedToken.jti == jti).first()
        if is_revoked:
            raise HTTPException(
                status_code=status.HTTP_401_UNAUTHORIZED,
                detail="Token has been revoked. Please log in again.",
                headers={"WWW-Authenticate": "Bearer"},
            )

    email: str = payload.get("sub")
    user = db.query(User).filter(User.email == email).first()
    if not user:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authenticated user no longer exists",
            headers={"WWW-Authenticate": "Bearer"},
        )

    if not user.is_active:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="User account is deactivated. Please contact an administrator."
        )

    return user


def get_optional_current_user(token: Optional[str] = Depends(oauth2_scheme), db: Session = Depends(get_db)) -> Optional[User]:
    """
    Returns the authenticated user if a valid token is provided, or None if unauthenticated.
    Used for endpoints that provide guest previews or public demonstrations.
    """
    if not token:
        return None
    try:
        return get_current_user(token=token, db=db)
    except HTTPException:
        return None


def require_role(allowed_roles: list[str]):
    """
    Role-based authorization dependency.
    Validates user role against the permitted roles list.
    """
    def role_checker(user: User = Depends(get_current_user)) -> User:
        if not user or user.role not in allowed_roles:
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail=f"Operation not permitted. Required role in {allowed_roles}, your role: {getattr(user, 'role', 'none')}"
            )
        return user
    return role_checker
